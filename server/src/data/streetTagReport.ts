/**
 * npm run report:street-tags -- <city>
 *
 * Which tags appear on the city's walkable streets, and on how much of their length.
 * Used to choose the street preferences the app supports from data, not from memory.
 * Writes docs/street-tags-<city>.md.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createOSMStream } from "osm-pbf-parser-node";
import { loadCityConfig } from "./buildCity.js";
import { haversineMeters } from "./geo.js";
import { isWalkable } from "./walkable.js";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const cityId = process.argv[2] ?? "cluj-napoca";
const config = await loadCityConfig(cityId);
const b = config.bbox;
const extract = path.join(ROOT, "server", "data", "raw", path.basename(new URL(config.extractUrl).pathname));

const coords = new Map<number, [number, number]>();
/** Tags on nodes inside the city, for point features on streets (kerbs, crossings). */
const nodeTags = new Map<number, Record<string, string>>();
const keyLength = new Map<string, number>();
const valueLength = new Map<string, Map<string, number>>();
const walkNodes = new Set<number>();
let totalLength = 0;
let ways = 0;

const started = Date.now();
for await (const item of createOSMStream(extract) as AsyncIterable<any>) {
  if (item.type === "node") {
    if (item.lat < b.south || item.lat > b.north || item.lon < b.west || item.lon > b.east) continue;
    coords.set(item.id, [item.lat, item.lon]);
    if (item.tags && Object.keys(item.tags).length) nodeTags.set(item.id, item.tags);
  } else if (item.type === "way") {
    const tags = item.tags as Record<string, string> | undefined;
    if (!tags || !isWalkable(tags)) continue;
    let len = 0;
    for (let i = 1; i < item.refs.length; i++) {
      const a = coords.get(item.refs[i - 1]), c = coords.get(item.refs[i]);
      if (a && c) len += haversineMeters(a[0], a[1], c[0], c[1]);
    }
    if (len === 0) continue;
    ways++;
    totalLength += len;
    for (const r of item.refs) if (coords.has(r)) walkNodes.add(r);
    for (const [k, v] of Object.entries(tags)) {
      keyLength.set(k, (keyLength.get(k) ?? 0) + len);
      let m = valueLength.get(k);
      if (!m) valueLength.set(k, (m = new Map()));
      m.set(v, (m.get(v) ?? 0) + len);
    }
  } else if (item.type === "relation") {
    break;
  }
}

// Point features on the walkable network.
const nodeKeyCount = new Map<string, number>();
const nodeValueCount = new Map<string, Map<string, number>>();
for (const id of walkNodes) {
  const t = nodeTags.get(id);
  if (!t) continue;
  for (const [k, v] of Object.entries(t)) {
    nodeKeyCount.set(k, (nodeKeyCount.get(k) ?? 0) + 1);
    let m = nodeValueCount.get(k);
    if (!m) nodeValueCount.set(k, (m = new Map()));
    m.set(v, (m.get(v) ?? 0) + 1);
  }
}

const pct = (x: number) => ((100 * x) / totalLength).toFixed(2);
const topValues = (m: Map<string, number> | undefined, n: number, asPct: boolean) =>
  [...(m ?? new Map()).entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, n)
    .map(([v, x]) => `${v} (${asPct ? pct(x) + "%" : x})`)
    .join(", ");

const isName = (k: string) => /^(name|alt_name|old_name|official_name|loc_name|short_name|int_name|ref|wikidata|wikipedia|source|note|fixme|check_date|survey|is_in)/.test(k);
const wayKeys = [...keyLength.entries()].filter(([k]) => !isName(k)).sort((a, b) => b[1] - a[1]);
const nodeKeys = [...nodeKeyCount.entries()].filter(([k]) => !isName(k)).sort((a, b) => b[1] - a[1]);

const lines: string[] = [];
lines.push(`# Tags on walkable streets — ${config.name}`);
lines.push("");
lines.push(`Generated by \`npm run report:street-tags -- ${cityId}\` on ${new Date().toISOString().slice(0, 10)} from \`${path.basename(extract)}\`.`);
lines.push(`Walkable ways (same rule as the city build): ${ways.toLocaleString("en")}, total length ${(totalLength / 1000).toFixed(0)} km.`);
lines.push("Names, references and bookkeeping tags (source, note, check_date…) are left out.");
lines.push("");
lines.push("## Tags on street segments (share of walkable length that has the key)");
lines.push("");
lines.push("| Key | Coverage | Most common values (share of all walkable length) |");
lines.push("|---|---|---|");
for (const [k, len] of wayKeys.filter(([, l]) => (100 * l) / totalLength >= 0.1).slice(0, 60)) {
  lines.push(`| \`${k}\` | ${pct(len)}% | ${topValues(valueLength.get(k), 6, true)} |`);
}
lines.push("");
lines.push(`## Tags on points of the walkable network (${walkNodes.size.toLocaleString("en")} nodes)`);
lines.push("");
lines.push("| Key | Nodes | Most common values (node count) |");
lines.push("|---|---|---|");
for (const [k, n] of nodeKeys.filter(([, n]) => n >= 20).slice(0, 40)) {
  lines.push(`| \`${k}\` | ${n.toLocaleString("en")} | ${topValues(nodeValueCount.get(k), 6, false)} |`);
}

const out = path.join(ROOT, "docs", `street-tags-${cityId}.md`);
await writeFile(out, lines.join("\n") + "\n");
console.log(`Wrote ${out} in ${((Date.now() - started) / 1000).toFixed(0)} s`);
