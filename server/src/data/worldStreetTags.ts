/**
 * npm run report:street-tags-world
 *
 * Which keys appear on walkable streets worldwide, from OSM taginfo
 * (taginfo.openstreetmap.org, whole-planet statistics). Counts are numbers of
 * ways (taginfo has no lengths), summed over all walkable highway values.
 * Writes docs/street-tags-world.md.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const API = "https://taginfo.openstreetmap.org/api/4";
const HEADERS = { "User-Agent": "walk-planner-thesis-research/0.1" };

/** The same highway values the city build treats as walkable (walkable.ts). */
const HIGHWAYS = [
  "footway", "pedestrian", "path", "steps", "living_street", "residential", "service",
  "unclassified", "tertiary", "secondary", "primary", "track", "cycleway", "bridleway",
  "corridor", "road", "tertiary_link", "secondary_link", "primary_link",
];

async function get<T>(url: string): Promise<T> {
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  return (await res.json()) as T;
}

interface Combo { other_key: string; other_value: string; together_count: number }

let totalWays = 0;
let dataUntil = "";
const byKey = new Map<string, number>();
const perHighway: Array<{ value: string; ways: number }> = [];

for (const value of HIGHWAYS) {
  const stats = await get<{ data_until: string; data: Array<{ type: string; count: number }> }>(
    `${API}/tag/stats?key=highway&value=${value}`,
  );
  dataUntil = stats.data_until;
  const ways = stats.data.find((d) => d.type === "ways")?.count ?? 0;
  totalWays += ways;
  perHighway.push({ value, ways });
  const combos = await get<{ data: Combo[] }>(
    `${API}/tag/combinations?key=highway&value=${value}&filter=ways&sortname=together_count&sortorder=desc&rp=150&page=1`,
  );
  for (const c of combos.data) {
    if (c.other_value !== "") continue; // key-level rows only
    byKey.set(c.other_key, (byKey.get(c.other_key) ?? 0) + c.together_count);
  }
  await new Promise((r) => setTimeout(r, 300)); // be gentle with a volunteer-run service
}

const isBookkeeping = (k: string) =>
  /^(name|alt_name|old_name|official_name|loc_name|short_name|int_name|ref|wikidata|wikipedia|source|note|fixme|check_date|survey|is_in|tiger:|gnis:|nhd|lacounty|osm_|import|created_by|attribution|maaamet|massgis|yh:|nysgissam|NHS|HFCS|kvl_hro|bag:|addr:|description|operator|mapillary)/i.test(k);

const rows = [...byKey.entries()]
  .filter(([k]) => !isBookkeeping(k))
  .sort((a, b) => b[1] - a[1])
  .slice(0, 50);

const lines = [
  "# Tags on walkable streets — worldwide",
  "",
  `Generated by \`npm run report:street-tags-world\` on ${new Date().toISOString().slice(0, 10)} from OSM taginfo (data until ${dataUntil}).`,
  `Walkable ways worldwide (highway = ${HIGHWAYS.join(", ")}): ${totalWays.toLocaleString("en")}.`,
  "Share = ways that carry the key / all walkable ways. Counted per way, not per metre (taginfo has no lengths).",
  "Names, references, imports and bookkeeping keys are left out. Keys outside each highway value's top 150 combinations are not counted, so small shares are lower bounds.",
  "",
  "| Key | Ways with the key | Share |",
  "|---|---|---|",
  ...rows.map(([k, n]) => `| \`${k}\` | ${n.toLocaleString("en")} | ${((100 * n) / totalWays).toFixed(2)}% |`),
  "",
  "## Walkable ways by highway value",
  "",
  "| highway | Ways |",
  "|---|---|",
  ...perHighway.sort((a, b) => b.ways - a.ways).map((h) => `| ${h.value} | ${h.ways.toLocaleString("en")} |`),
];
const out = path.join(ROOT, "docs", "street-tags-world.md");
await writeFile(out, lines.join("\n") + "\n");
console.log(`Wrote ${out}`);
